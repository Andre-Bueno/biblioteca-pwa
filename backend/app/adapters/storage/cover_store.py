"""Downloaded series covers on disk: `<DATA_DIR>/covers/<series uuid>.<jpg|png|webp>`.

The file name is built ONLY from the series UUID (generated by the server) and an extension derived
from the image's magic bytes. Nothing from the network, the database or a client ever becomes part
of a path: names read back from the database are re-validated against the same pattern. A write is
staged in a temporary file (exclusive create, fsync) and moved with an atomic rename, so a reader
never sees a half-written cover.
"""

import contextlib
import os
import re
import secrets
from pathlib import Path

from app.domain.errors import ExternalFetchError, UnsafePath
from app.domain.library import Page
from app.domain.metadata import FetchedImage, StagedCover, sniff_image

COVERS_DIRNAME = "covers"
MAX_COVER_BYTES = 5 * 1024 * 1024
_NAME = re.compile(
    r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(?:jpg|png|webp)"
)
_UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
_TOKEN = re.compile(r"[0-9a-f]{16}")
_EXTENSIONS = frozenset({"jpg", "png", "webp"})


class LocalCoverStore:
    def __init__(self, data_dir: Path, *, max_bytes: int = MAX_COVER_BYTES) -> None:
        self._dir = Path(data_dir) / COVERS_DIRNAME
        self._max_bytes = max_bytes

    def _final(self, rel_path: str) -> Path | None:
        if _NAME.fullmatch(rel_path) is None:
            return None
        return self._dir / rel_path

    def _temp(self, token: str) -> Path:
        if _TOKEN.fullmatch(token) is None:
            raise UnsafePath("invalid cover token")
        return self._dir / f".{token}.tmp"

    def stage(self, series_id: str, image: FetchedImage) -> StagedCover:
        if _UUID.fullmatch(series_id) is None or image.ext not in _EXTENSIONS:
            raise UnsafePath("invalid cover name")
        if len(image.data) > self._max_bytes:
            raise ExternalFetchError("too_large")
        self._dir.mkdir(parents=True, exist_ok=True)
        token = secrets.token_hex(8)
        temp = self._temp(token)
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
        fd = os.open(temp, flags, 0o600)
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(image.data)
                handle.flush()
                os.fsync(handle.fileno())
        except BaseException:
            temp.unlink(missing_ok=True)
            raise
        return StagedCover(series_id=series_id, rel_path=f"{series_id}.{image.ext}", token=token)

    def commit(self, staged: StagedCover) -> None:
        final = self._final(staged.rel_path)
        if final is None:
            raise UnsafePath("invalid cover name")
        os.replace(self._temp(staged.token), final)

    def discard(self, staged: StagedCover) -> None:
        self._temp(staged.token).unlink(missing_ok=True)

    def read(self, rel_path: str) -> Page | None:
        path = self._final(rel_path)
        if path is None:
            return None
        try:
            if path.is_symlink() or not path.is_file() or path.stat().st_size > self._max_bytes:
                return None
            data = path.read_bytes()
        except OSError:
            return None
        sniffed = sniff_image(data)
        return None if sniffed is None else Page(data=data, media_type=sniffed[0])

    def delete(self, rel_path: str) -> None:
        path = self._final(rel_path)
        if path is None:
            return
        with contextlib.suppress(OSError):
            path.unlink(missing_ok=True)
